// Generates the simple case folding tables used to detect case-only path
// collisions (src/casefold-data.ts and rust/src/casefold_data.rs) from the
// Unicode Character Database's CaseFolding.txt.
//
//   curl -sSfLO https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt
//   node tools/gen-casefold.mjs CaseFolding.txt
//
// Only status C (common) and S (simple) mappings are used: that is Unicode
// "simple case folding", one code point to one code point. F (full, e.g.
// ß -> ss) and T (Turkic dotted/dotless i) mappings are left out. The table is
// written as runs [start, end, delta, step]: every code point c with
// start <= c <= end and (c - start) % step == 0 folds to c + delta. Both
// files hold exactly the same runs.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const input = process.argv[2];
if (!input) {
  console.error('usage: node tools/gen-casefold.mjs CaseFolding.txt');
  process.exit(2);
}
const text = readFileSync(input, 'utf8');
const version = /^# CaseFolding-([\d.]+)\.txt/m.exec(text)?.[1];
if (!version) throw new Error('not a CaseFolding.txt (no version header)');

const map = [];
for (const line of text.split('\n')) {
  const body = line.split('#')[0].trim();
  if (!body) continue;
  const [code, status, mapping] = body.split(';').map((s) => s.trim());
  if (status !== 'C' && status !== 'S') continue;
  const to = mapping.split(' ');
  if (to.length !== 1) throw new Error(`simple mapping with ${to.length} code points: ${line}`);
  map.push([parseInt(code, 16), parseInt(to[0], 16)]);
}
map.sort((a, b) => a[0] - b[0]);

// Greedy runs: extend while the next mapping has the same delta and stride.
const runs = [];
let i = 0;
while (i < map.length) {
  const [start, to] = map[i];
  const delta = to - start;
  let end = start;
  let step = 1;
  let j = i + 1;
  if (j < map.length && map[j][1] - map[j][0] === delta && map[j][0] - start <= 2) {
    step = map[j][0] - start;
    while (j < map.length && map[j][1] - map[j][0] === delta && map[j][0] - end === step) {
      end = map[j][0];
      j++;
    }
  }
  runs.push([start, end, delta, step]);
  i = j;
}

// Lookups binary-search on `start`, so runs must not overlap.
for (let k = 1; k < runs.length; k++) {
  if (runs[k][0] <= runs[k - 1][1]) throw new Error(`overlapping runs at U+${runs[k][0].toString(16)}`);
}

// Self-check: the runs reproduce the mapping exactly.
const fold = (c) => {
  for (const [s, e, d, st] of runs) if (c >= s && c <= e && (c - s) % st === 0) return c + d;
  return c;
};
const want = new Map(map);
for (let c = 0; c <= 0x10ffff; c++) {
  if (fold(c) !== (want.get(c) ?? c)) throw new Error(`run table wrong at U+${c.toString(16)}`);
}

const header = [
  `// GENERATED by tools/gen-casefold.mjs from CaseFolding-${version}.txt; do not edit.`,
  `// Unicode simple case folding (status C and S): ${map.length} mappings in ${runs.length} runs`,
  `// [start, end, delta, step]: c in start..=end with (c - start) % step == 0 folds to c + delta.`,
].join('\n');

const ts = `${header}

export const CASEFOLD_UNICODE_VERSION = '${version}';

// prettier-ignore
export const CASEFOLD_RUNS: ReadonlyArray<readonly [number, number, number, number]> = [
${runs.map((r) => `  [${r.join(', ')}],`).join('\n')}
];
`;
const rs = `${header}

pub const CASEFOLD_UNICODE_VERSION: &str = "${version}";

#[rustfmt::skip]
pub const CASEFOLD_RUNS: &[(u32, u32, i32, u32)] = &[
${runs.map((r) => `    (${r.join(', ')}),`).join('\n')}
];
`;
writeFileSync(path.join(root, 'src/casefold-data.ts'), ts);
writeFileSync(path.join(root, 'rust/src/casefold_data.rs'), rs);
console.log(`CaseFolding ${version}: ${map.length} mappings, ${runs.length} runs`);
